#!/usr/bin/env python3
"""Answer-quality grading for the queries that carry assertions in queries.json.

Complements analyze.py: analyze.py measures *triggering and grounding* (did the
skill fire, were jeap_* calls made); this script measures whether the final
answer is actually *right*. Each assertion states corpus-verified ground truth
for its query, and an LLM judge (`claude -p`, no tools) checks it against the
run's final answer — so a run that triggered, grounded, and then produced a
plausible-but-wrong diagnosis is caught here instead of passing silently.
Assertions on should-not-trigger queries grade the flip side: that a (soft)
misfire still ended in a correct non-jEAP answer.

Grades the Claude transcripts (results/claude/<id>.jsonl) by default; select
with --sources, e.g. `--sources copilot` for the Copilot A-variant transcripts
(results/copilot/<id>--A-with-skill.md) without re-judging the Claude ones.
Writes grading.json next to the transcripts and prints a pass/fail table.
Judge calls bill the logged-in claude account; queries without a transcript in
the workdir are skipped, so partial runs grade fine.
"""
import argparse, json, re, subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent

FIXTURE_KIND = {
    "jeap-fixture": "a jEAP-based Spring Boot project (Maven parent jeap-spring-boot-parent, jEAP starters, jeap.* properties)",
    "plain-fixture": "a plain Spring Boot project without any jEAP usage",
    "neutral": "an empty directory with no project",
}

JUDGE_PROMPT = """You are grading one answer from an automated eval of a jEAP developer-assistant skill.

The user asked, from {kind}:
<question>
{q}
</question>

The assistant's final answer was:
<answer>
{answer}
</answer>

Grade the answer against each assertion below, strictly and only from the answer text.
The assertions state corpus-verified ground truth. An answer fails an assertion if it
contradicts it or simply does not contain what the assertion requires; do not give
credit for vagueness.

Assertions:
{assertions}

Do not use any tools. Reply with ONLY a JSON array, one object per assertion, in the
same order, of the form:
[{{"text": "<the assertion>", "passed": true|false, "evidence": "<short quote or reason>"}}]
"""


def final_answer_claude(path):
    answer, last_text = None, None
    for line in path.open():
        try:
            ev = json.loads(line)
        except json.JSONDecodeError:
            continue
        if ev.get("type") == "result" and isinstance(ev.get("result"), str):
            answer = ev["result"]
        elif ev.get("type") == "assistant":
            for c in ev.get("message", {}).get("content", []):
                if c.get("type") == "text" and c.get("text", "").strip():
                    last_text = c["text"]
    return answer or last_text


def final_answer_copilot(path):
    parts = re.split(r"^### 💬 Copilot\s*$", path.read_text(), flags=re.M)
    if len(parts) < 2:
        return None
    ans = re.sub(r"\n---\s*\n<sub>Generated by.*$", "", parts[-1], flags=re.S)
    return ans.strip() or None


def judge(item, answer, model):
    prompt = JUDGE_PROMPT.format(
        kind=FIXTURE_KIND[item["dir"]], q=item["q"], answer=answer,
        assertions="\n".join(f"{i+1}. {a}" for i, a in enumerate(item["assertions"])))
    r = subprocess.run(["claude", "-p", prompt, "--output-format", "json",
                        "--model", model, "--max-turns", "3"],
                       capture_output=True, text=True, cwd=HERE, timeout=300)
    if r.returncode != 0:
        raise RuntimeError(f"judge failed rc={r.returncode}: {r.stderr[:500]}")
    text = json.loads(r.stdout)["result"]
    m = re.search(r"\[.*\]", text, re.S)
    verdicts = json.loads(m.group(0))
    if len(verdicts) != len(item["assertions"]):
        raise RuntimeError(f"judge returned {len(verdicts)} verdicts "
                           f"for {len(item['assertions'])} assertions")
    return verdicts


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--workdir", default=str(HERE / "workdir"))
    parser.add_argument("--model", default="sonnet", help="judge model for claude -p")
    parser.add_argument("--sources", nargs="+", choices=["claude", "copilot"],
                        default=["claude"],
                        help="which harness transcripts to grade (default: claude)")
    parser.add_argument("--ids", nargs="*", help="grade only these query ids")
    args = parser.parse_args()

    queries = [q for q in json.loads((HERE / "queries.json").read_text())
               if q.get("assertions") and (not args.ids or q["id"] in args.ids)]
    results_dir = Path(args.workdir) / "results"
    all_sources = {
        "claude": (results_dir / "claude", "{id}.jsonl", final_answer_claude),
        "copilot": (results_dir / "copilot", "{id}--A-with-skill.md", final_answer_copilot),
    }
    sources = [(n, *all_sources[n]) for n in args.sources]

    grand_pass = grand_total = 0
    for name, src_dir, pattern, extract in sources:
        if not src_dir.is_dir():
            print(f"[{name}] no results at {src_dir} — skipped")
            continue
        print(f"=== Answer grading: {name} ===")
        grading = {}
        for item in queries:
            path = src_dir / pattern.format(id=item["id"])
            if not path.exists():
                print(f"{item['id']:28} no transcript — skipped")
                continue
            answer = extract(path)
            if not answer:
                print(f"{item['id']:28} no final answer in transcript — skipped")
                continue
            verdicts = judge(item, answer, args.model)
            passed = sum(1 for v in verdicts if v.get("passed"))
            grading[item["id"]] = {"expect_trigger": item["expect"],
                                   "assertions": verdicts}
            grand_pass += passed
            grand_total += len(verdicts)
            print(f"{item['id']:28} {passed}/{len(verdicts)} assertions passed")
            for v in verdicts:
                mark = "PASS" if v.get("passed") else "FAIL"
                print(f"    {mark}  {v.get('text', '')[:100]}")
                if not v.get("passed"):
                    print(f"          -> {v.get('evidence', '')[:200]}")
        if grading:
            out = src_dir / "grading.json"
            merged = json.loads(out.read_text()) if out.exists() else {}
            merged.update(grading)
            out.write_text(json.dumps(merged, indent=1))
            print(f"[{name}] written: {out}\n")
    if grand_total:
        print(f"TOTAL: {grand_pass}/{grand_total} assertions passed")


if __name__ == "__main__":
    main()
